export const LANGUAGE_STORAGE_KEY = 'hs_language';

export function loadStoredLanguage(): LanguageCode {
  if (typeof window === 'undefined') return 'en';
  try {
    const raw = localStorage.getItem(LANGUAGE_STORAGE_KEY) as LanguageCode | null;
    if (raw && LANGUAGE_OPTIONS.some((l) => l.code === raw)) {
      return raw;
    }
  } catch {
    // ignore storage errors
  }
  return 'en';
}

export function saveStoredLanguage(code: LanguageCode): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, code);
  } catch {
    // ignore storage errors
  }
}

